<script>
  document.addEventListener('DOMContentLoaded', function () {

    /* ---------------------------
       Smooth Scrolling for Links
    ---------------------------- */
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
      anchor.addEventListener('click', function (e) {
        const selector = this.getAttribute('href');
        if (!selector || selector === '#') {
          return;
        }
        e.preventDefault();
        const target = document.querySelector(selector);
        if (target) {
          target.scrollIntoView({
            behavior: 'smooth',
            block: 'start'
          });
        }
      });
    });

    /* ---------------------------
       Search Form Functionality
    ---------------------------- */
    const searchForm = document.querySelector('form.d-flex');
    if (searchForm) {
      searchForm.addEventListener('submit', function (e) {
        e.preventDefault();
        const searchTerm = this.querySelector('input[type="search"]').value.trim();
        if (searchTerm) {
          window.location.href = `search.php?q=${encodeURIComponent(searchTerm)}`;
        }
      });
    }

    /* ---------------------------
       Newsletter Subscription Form
    ---------------------------- */
    const newsletterForm = document.querySelector('section.bg-primary form');
    if (newsletterForm) {
      newsletterForm.addEventListener('submit', function (e) {
        e.preventDefault();
        const email = this.querySelector('input[type="email"]').value.trim();
        if (email) {
          alert('Thank you for subscribing! You will receive updates about our courses and events.');
          this.querySelector('input[type="email"]').value = '';
        }
      });
    }

    /* ---------------------------
       Course Card Hover Animation
    ---------------------------- */
    document.querySelectorAll('.card').forEach(card => {
      card.addEventListener('mouseenter', function () {
        this.style.transform = 'translateY(-5px)';
        this.style.transition = 'transform 0.3s ease';
      });
      card.addEventListener('mouseleave', function () {
        this.style.transform = 'translateY(0)';
      });
    });

    /* ---------------------------
       Navbar Scroll + Back to Top
    ---------------------------- */
    const navbar = document.querySelector('.navbar');
    const backToTopButton = document.getElementById('backToTopButton');

    window.addEventListener('scroll', function () {
      const scrollY = window.scrollY;

      // Navbar background effect
      if (navbar) {
        if (scrollY > 50) navbar.classList.add('navbar-scrolled');
        else navbar.classList.remove('navbar-scrolled');
      }

      // Back to Top button visibility
      if (backToTopButton) {
        backToTopButton.style.display = scrollY > 200 ? 'flex' : 'none';
      }
    });

    /* ---------------------------
       Auto-Close Mobile Menu
    ---------------------------- */
    document.querySelectorAll('.navbar-nav .nav-link').forEach(link => {
      link.addEventListener('click', function () {
        const navbarToggler = document.querySelector('.navbar-toggler');
        const navbarCollapse = document.querySelector('.navbar-collapse');
        if (navbarToggler && navbarCollapse && window.getComputedStyle(navbarToggler).display !== 'none') {
          navbarCollapse.classList.remove('show');
        }
      });
    });

    /* ---------------------------
       Chat Box Toggle & Send
    ---------------------------- */
    window.toggleChatBox = function () {
      const chatBox = document.getElementById('chatBox');
      if (chatBox) {
        chatBox.style.display = (chatBox.style.display === 'none' || chatBox.style.display === '') ? 'block' : 'none';
      }
    };

    window.sendChatMessage = function () {
      const input = document.getElementById('chatInput');
      const message = input?.value.trim();
      const chatBody = document.querySelector('#chatBox .card-body');

      if (message && chatBody) {
        const msgElement = document.createElement('div');
        msgElement.classList.add('text-end', 'mb-2');
        msgElement.innerHTML = `<span class="badge bg-info text-white p-2">${message}</span>`;
        chatBody.appendChild(msgElement);
        input.value = '';
        chatBody.scrollTop = chatBody.scrollHeight;
      }
    };

    /* ---------------------------
       Scroll to Top Function
    ---------------------------- */
    window.scrollToTop = function () {
      window.scrollTo({ top: 0, behavior: 'smooth' });
    };

  });
</script>

